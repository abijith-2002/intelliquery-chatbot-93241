class ChatRequest(BaseModel):
    """Schema for a chat request."""
    session_id: str = Field(..., description="Unique session identifier for the conversation context.")
    query: str = Field(..., description="User's query (question or message).")


class ChatResponse(BaseModel):
    """Schema for the chat response."""
    rag_answer: str = Field(..., description="Retrieved answer from the RAG knowledge base.")
    gemini_answer: str = Field(..., description="Enhanced answer generated by Gemini API.")
    conversation_history: List[dict] = Field(..., description="Full chat context for this session.")


