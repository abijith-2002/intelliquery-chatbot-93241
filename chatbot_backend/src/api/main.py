@app.get(
    "/chat/history/{session_id}",
    tags=["Chat"],
    summary="Get chat history for a session",
    description="Return chronological chat messages for the specified session.",
    response_model=List[HistoryItem],
)
def chat_history(session_id: str, db=Depends(get_db)):
    """
    PUBLIC_INTERFACE
    Retrieve chat history for a given session_id from the database.

    Args:
        session_id (str): The session identifier for the conversation.
        db (Session): SQLAlchemy Session dependency.

    Returns:
        List[HistoryItem]: List of messages mapped to 'human' (user) and 'ai' (assistant) with timestamps.
    """
    if not session_id or not isinstance(session_id, str):
        raise HTTPException(status_code=400, detail="session_id must be a non-empty string.")
    rows = get_messages_for_session(db, session_id=session_id, limit=100)
    history: List[HistoryItem] = []
    for m in rows:
        role = (m.get("role") or "").lower()
        msg_type = "ai" if role == "assistant" else "human"
        content = str(m.get("content") or "")
        history.append(HistoryItem(type=msg_type, content=content, created_at=m.get("created_at")))
    return history


