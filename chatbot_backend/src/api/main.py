@app.post(
    "/chat",
    response_model=ChatResponse,
    tags=["Chat"],
    summary="Chat with bot",
    description="Submit a chat query. Gemini always answers; a RAG knowledge base document is included as additional Gemini context if relevant; conversation history is always provided to Gemini for context."
)
def chat(request: ChatRequest, db=Depends(get_db)):
    """
    PUBLIC_INTERFACE
    Handles user's chat request. All answers come directly from Gemini.
    The current conversation history is always provided to Gemini to support follow-up queries or context-aware answers.
    """
    import traceback

    def _safe_str_output(val, fallback=""):
        if val is None or (isinstance(val, str) and val.strip() == ""):
            return fallback
        return str(val)

    try:
        session_id = request.session_id
        if not session_id or not isinstance(session_id, str):
            raise HTTPException(status_code=400, detail="session_id must be a non-empty string.")

        # Ensure in-memory context exists and hydrate it from DB if it's new/empty
        if session_id not in CONVERSATION_MEMORY:
            CONVERSATION_MEMORY[session_id] = ConversationBufferMemory(
                return_messages=True,
                output_key="output"
            )
        memory = CONVERSATION_MEMORY[session_id]

        try:
            msgs = getattr(memory, "chat_memory").messages if hasattr(memory, "chat_memory") else []
            if not msgs:
                # Hydrate memory from DB history (pair user->assistant turns)
                db_msgs = get_messages_for_session(db, session_id=session_id, limit=100)
                last_user = None
                for m in db_msgs:
                    role = (m.get("role") or "").lower()
                    content = (m.get("content") or "")
                    if role == "user":
                        last_user = content
                    elif role == "assistant":
                        if last_user is not None:
                            memory.save_context({"input": last_user}, {"output": content})
                            last_user = None
                # If trailing user message without assistant, store with placeholder so context retains it
                if last_user is not None:
                    memory.save_context({"input": last_user}, {"output": "No answer available"})
        except Exception:
            # Do not hard fail; proceed even if hydration fails
            pass

        # Ensure a conversation exists in DB
        convo = get_or_create_conversation(db, session_id=session_id, user_id=None, title=None)

        # Persist the user message to DB (no placeholder memory write)
        create_message(db, conversation_id=convo.id, role="user", content=_safe_str_output(request.query))

        # RAG retrieval
        qa = rag_retrieve(request.query, QA_LIST)
        rag_weak_match = qa.get("weak_match", False)
        kb_q = qa.get("q", "")
        kb_a = qa.get("a", "")
        if kb_a != "":
            rag_answer = kb_a
        elif kb_q != "" and rag_weak_match:
            rag_answer = ""
        else:
            rag_answer = ""

        # Compose Gemini answer (context from hydrated memory; current input is passed explicitly)
        try:
            gemini_answer = get_gemini_response(request.query, rag_answer, memory)
        except Exception as e:
            gemini_answer = "[Gemini unavailable: {}]\n{}".format(e, rag_answer or "")

        # Final output cleaning for defense-in-depth
        gemini_answer = clean_gemini_output(_safe_str_output(gemini_answer, ""))

        # Save the final turn to memory and DB (single, consistent write)
        try:
            memory.save_context({"input": request.query}, {"output": gemini_answer})
        except Exception:
            # Memory write errors should not break the request
            pass

        try:
            create_message(db, conversation_id=convo.id, role="assistant", content=gemini_answer)
        except Exception:
            # DB write error for assistant shouldn't break the request if user message already persisted
            pass

        # Prepare conversation history for output (last 20 messages) from DB
        conversation_history: List[dict] = []
        try:
            history = get_messages_for_session(db, session_id=session_id, limit=20)
            for m in history:
                role = (m.get("role") or "").lower()
                content = _safe_str_output(m.get("content"))
                msg_type = "ai" if role == "assistant" else "human"
                conversation_history.append(
                    {"type": msg_type, "content": content}
                )
        except Exception:
            # Fallback to memory if DB history fails
            if hasattr(memory, "chat_memory") and hasattr(memory.chat_memory, "messages"):
                for m in memory.chat_memory.messages[-20:]:
                    m_dict = {}
                    if hasattr(m, "type") and hasattr(m, "content"):
                        m_dict = {"type": m.type, "content": _safe_str_output(m.content)}
                    conversation_history.append(m_dict)

        return ChatResponse(
            rag_answer=_safe_str_output(rag_answer),  # Could be empty str
            gemini_answer=gemini_answer,              # Gemini's answer, cleaned of meta/source
            conversation_history=conversation_history
        )

    except HTTPException:
        raise  # Allow FastAPI HTTPExceptions to propagate
    except Exception as e:
        tb = traceback.format_exc()
        print(f"Internal Server Error in /chat endpoint: {e}\nTraceback:\n{tb}")
        raise HTTPException(status_code=500, detail=f"Internal Server Error: {e}")


